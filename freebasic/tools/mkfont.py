#!/usr/bin/env python3
"""Turn tools/font.txt into src/font.bi: a width and 11 rows of bits per
character. Usage: mkfont.py tools/font.txt src/font.bi"""
import sys

SPECIAL = {"SP": 32, "AT": 64, "HASH": 35, "DEG": 176, "DOT": 183}
H = 11
glyphs = {}
cur = None
for line in open(sys.argv[1], encoding="utf-8"):
    line = line.rstrip("\n")
    if line.startswith("@"):
        tok, w, top = line[1:].split(" ")
        if tok.startswith("0x"):
            code = int(tok, 16)        # a Windows-1252 code, e.g. 0xD7 for the times sign
        else:
            code = SPECIAL.get(tok, ord(tok) if len(tok) == 1 else None)
        if code is None:
            sys.exit(f"bad glyph name {tok!r}")
        cur = glyphs[code] = {"w": int(w), "top": int(top), "rows": []}
    elif cur is not None and line and line[0] in "#.":
        if len(line) != cur["w"]:
            sys.exit(f"glyph {chr(code)!r}: row {line!r} is not {cur['w']} wide")
        if len(line) > 8:
            sys.exit(f"glyph {chr(code)!r}: wider than the 8 bits a row has")
        cur["rows"].append(line)

missing = [chr(c) for c in range(33, 127) if c not in glyphs]
if missing:
    sys.exit("missing glyphs: " + " ".join(missing))

widths, bits = [], []
for c in range(256):
    g = glyphs.get(c)
    if g is None:
        widths.append(0)
        bits.append([0] * H)
        continue
    rows = [0] * H
    for i, r in enumerate(g["rows"]):
        v = 0
        for x, ch in enumerate(r):
            if ch == "#":
                v |= 1 << x
        rows[g["top"] + i] = v
    widths.append(g["w"])
    bits.append(rows)

with open(sys.argv[2], "w") as f:
    f.write("' Generated by tools/mkfont.py from tools/font.txt. Do not edit.\n")
    f.write(f"Const FONT_H = {H}\n")
    f.write("Dim Shared FontW(0 To 255) As UByte = { _\n")
    f.write(", _\n".join("    " + ", ".join(str(w) for w in widths[i:i + 32]) for i in range(0, 256, 32)))
    f.write(" }\n")
    f.write(f"Dim Shared FontBits(0 To 255, 0 To {H - 1}) As UByte = {{ _\n")
    f.write(", _\n".join("    {" + ", ".join(str(v) for v in b) + "}" for b in bits))
    f.write(" }\n")
print(f"{len(glyphs)} glyphs")
