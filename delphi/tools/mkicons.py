#!/usr/bin/env python3
"""Copy the toolbar icons (16x16 text pixel art) out of the VB version's
modIcons.bas into src/icondata.inc, so every edition shares the same art.
Usage: mkicons.py <path to modIcons.bas> src/icondata.inc"""
import re, sys
icons, key = {}, None
for line in open(sys.argv[1], encoding="latin-1"):
    m = re.match(r'\s*Case "([^"]+)"', line)
    if m:
        key = m.group(1); icons[key] = []; continue
    m = re.match(r'\s*R "([0-9A-F.]{16})"', line)
    if m and key:
        icons[key].append(m.group(1))
icons = {k: v for k, v in icons.items() if len(v) == 16}
with open(sys.argv[2], "w") as f:
    f.write("{ Generated by tools/mkicons.py from the VB version's modIcons.bas.\n")
    f.write("  16 rows of 16: a hex digit is a QBColor index, '.' is see-through. }\n")
    f.write(f"const\n  ICON_COUNT = {len(icons)};\n")
    f.write(f"  IconNames: array[0..{len(icons)-1}] of string = (" + ", ".join(f"'{k}'" for k in icons) + ");\n")
    f.write(f"  IconArt: array[0..{len(icons)-1}, 0..15] of string[16] = (\n")
    f.write(",\n".join("    (" + ", ".join(f"'{r}'" for r in rows) + ")" for rows in icons.values()))
    f.write(");\n")
print(len(icons), "icons")
