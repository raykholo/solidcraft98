#!/usr/bin/env python3
"""Reproduce the Rust const art directly from the FreeBASIC reference."""
from pathlib import Path
import re
root = Path(__file__).resolve().parents[2]
s = (root / 'freebasic/src/font.bi').read_text()
w, bits = s.split('Dim Shared FontBits')
widths = re.findall(r'\d+', w.split('= {')[1])
rows = re.findall(r'\{([\d, ]+)\}', bits)
p = root / 'rust/sc98-pixels/src'
(p / 'font.rs').write_text('// Generated by rust/tools/port-art.py from freebasic/src/font.bi.\n'
    + 'pub const HEIGHT: usize = 11;\npub const WIDTHS: [u8; 256] = [\n'
    + ', '.join(widths) + '\n];\npub const BITS: [[u8; 11]; 256] = [\n'
    + '\n'.join('[' + r + '],' for r in rows) + '\n];\n')
s = (root / 'freebasic/src/icons.bi').read_text()
names = re.findall(r'"([^"]+)"', s.split('IconName')[1].split('Dim Shared IconArt')[0])
rows = re.findall(r'"([.0-9A-F]{16})"', s.split('Dim Shared IconArt')[1])
(p / 'icons.rs').write_text('// Generated by rust/tools/port-art.py from freebasic/src/icons.bi.\n'
    + 'pub const NAMES: [&str; 17] = [' + ', '.join('"' + n + '"' for n in names) + '];\n'
    + '/// 255 is transparent; all other bytes are QB palette indices.\n'
    + 'pub const ART: [[u8; 256]; 17] = [\n'
    + '\n'.join('[' + ', '.join(str(255 if c == '.' else int(c, 16))
                   for row in rows[i:i+16] for c in row) + '],'
                   for i in range(0, len(rows), 16)) + '\n];\n')

# Keep regenerated const files identical to the formatted checked-in sources.
import subprocess
subprocess.run(["rustfmt", str(p / "font.rs"), str(p / "icons.rs")], check=True)
