#!/usr/bin/env python3
"""Verify FreeBASIC goldens, or regenerate them with --write (no Rust build)."""
import argparse
import hashlib
import os
from pathlib import Path
import shlex
import struct
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    source = Path(__file__).resolve().with_suffix(".bas")
    root = source.parents[3]
    fixtures = source.with_name("fixtures")
    designs = [
        ("Mounting Plate.sc98", "plate", 560),
        ("Plate with holes.solidcraft", "import-plate", 560),
        ("Revolved parts.solidcraft", "import-revolved", 466),
        ("Flange.solidcraft", "import-flange", 444),
    ]
    outputs = {}
    lines = [
        "# Generated by FreeBASIC 1.10.1, tests/reference.bas; 64 segments.",
        "# stem\tedges\ttriangles\tmesh FNV-1a64 (f32 vertices then u32 feature per triangle)\tSTL SHA-256",
    ]
    with tempfile.TemporaryDirectory(prefix="sc98-reference-") as folder:
        folder = Path(folder)
        exe = folder / "reference"
        compiler = os.environ.get("FBC", "fbc")
        flags = shlex.split(os.environ.get("FBC_FLAGS", ""))
        subprocess.run(
            ["nice", "-n", "10", compiler, *flags, "-w", "all", "-exx", str(source), "-x", str(exe)],
            cwd=folder, check=True,
        )
        for name, stem, edges in designs:
            out = folder / stem
            subprocess.run([str(exe), str(root / "samples" / name), str(out)], check=True)
            for ext in ["sc98", "stl"]:
                outputs[f"{stem}.{ext}"] = out.with_suffix(f".{ext}").read_bytes()
            raw = out.with_suffix(".tri").read_bytes()
            if len(raw) % 76:
                raise RuntimeError("Expected 9 doubles and a 32-bit feature per triangle")
            fingerprint = 0xCBF29CE484222325
            for at in range(0, len(raw), 76):
                record = struct.unpack_from("<9di", raw, at)
                for byte in struct.pack("<9fI", *record):
                    fingerprint = ((fingerprint ^ byte) * 0x100000001B3) & ((1 << 64) - 1)
            outputs[f"{stem}.mesh-fnv"] = f"{fingerprint}\n".encode()
            digest = hashlib.sha256(outputs[f"{stem}.stl"]).hexdigest()
            lines.append(f"{stem}\t{edges}\t{len(raw) // 76}\t{fingerprint:016x}\t{digest}")
    outputs["reference.tsv"] = ("\n".join(lines) + "\n").encode()
    for name, content in outputs.items():
        path = fixtures / name
        if args.write:
            path.write_bytes(content)
        elif path.read_bytes() != content:
            raise RuntimeError(f"Reference fixture differs: {name}")
    print(f"{'Wrote' if args.write else 'Verified'} {len(outputs)} FreeBASIC reference fixtures.")


if __name__ == "__main__":
    main()
